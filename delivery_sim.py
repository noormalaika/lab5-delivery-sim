import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Make results reproducible
np.random.seed(42)

# Generate 97 normal delivery times
normal_deliveries = np.random.normal(32, 7, 97)

# Keep normal deliveries in a reasonable range
normal_deliveries = np.clip(normal_deliveries, 15, 50)

# Add 3 unusually long deliveries
delivery_times = np.concatenate(
    [normal_deliveries, [68, 71, 75]]
)

# Create DataFrame
df = pd.DataFrame({
    "OrderID": range(1001, 1101),
    "DeliveryTime(min)": np.round(delivery_times, 1)
})

# Save CSV
df.to_csv("delivery_times.csv", index=False)

# Load CSV
df = pd.read_csv("delivery_times.csv")

# Mean and standard deviation
mean_time = df["DeliveryTime(min)"].mean()
std_time = df["DeliveryTime(min)"].std()

print(
    f"Real delivery times -- Mean: "
    f"{mean_time:.2f} min "
    f"Std: {std_time:.2f} min"
)

# Simulate 100 expected delivery times
simulated_times = np.random.normal(
    mean_time,
    std_time,
    100
)

print(
    f"Simulated 100 values from "
    f"Normal(mean={mean_time:.2f}, "
    f"std={std_time:.2f})"
)

# Missing values
print("\nMissing values:")
print(df.isnull().sum())

# Percentiles
q1 = df["DeliveryTime(min)"].quantile(0.25)
median = df["DeliveryTime(min)"].quantile(0.50)
q3 = df["DeliveryTime(min)"].quantile(0.75)

print(
    f"\nPercentiles -- "
    f"25th: {q1:.2f} "
    f"50th: {median:.2f} "
    f"75th: {q3:.2f}"
)

# Comparison histogram
plt.figure(figsize=(9, 5))

plt.hist(
    df["DeliveryTime(min)"],
    bins=15,
    alpha=0.6,
    label="Real Deliveries",
    edgecolor="black"
)

plt.hist(
    simulated_times,
    bins=15,
    alpha=0.6,
    label="Simulated Deliveries",
    edgecolor="black"
)

plt.xlabel("Delivery Time (minutes)")
plt.ylabel("Frequency")
plt.title("Real vs Simulated Delivery Times")
plt.legend()
plt.tight_layout()

plt.savefig(
    "delivery_comparison_histogram.png",
    dpi=300
)

plt.show()

# Boxplot
plt.figure(figsize=(8, 5))

plt.boxplot(df["DeliveryTime(min)"])

plt.ylabel("Delivery Time (minutes)")
plt.title("Boxplot of Delivery Times")
plt.tight_layout()

plt.savefig(
    "delivery_boxplot.png",
    dpi=300
)

plt.show()

# IQR method
iqr = q3 - q1

lower_bound = q1 - 1.5 * iqr
upper_bound = q3 + 1.5 * iqr

print(f"\nIQR: {iqr:.2f}")

print(
    f"IQR outlier bounds: "
    f"{lower_bound:.2f} - "
    f"{upper_bound:.2f}"
)

# Find outliers
outliers = df[
    (df["DeliveryTime(min)"] < lower_bound) |
    (df["DeliveryTime(min)"] > upper_bound)
]

print("\nOutliers detected:")

print(
    outliers[
        ["OrderID", "DeliveryTime(min)"]
    ]
)

print("\nNumber of outliers:", len(outliers))

percentage = (
    len(outliers) / len(df)
) * 100

print(
    f"Percentage flagged as outliers: "
    f"{percentage:.2f}%"
)

print(
    "\nSaved "
    "delivery_comparison_histogram.png "
    "and delivery_boxplot.png"
)